// npm run db:permissions
// Writes src/lib/db/migrations/0002_permissions_seed.sql from src/lib/permissions.ts, so the matrix the UI uses
// and the matrix the database enforces cannot drift. A test (tests/db/permissions-parity.test.ts) fails if they do.
import fs from "node:fs";
import { MATRIX, ROLE_DB, type Role } from "../src/lib/permissions";

export const ROLE_ENUM = ROLE_DB;

export function permissionsSql(): string {
  const rows = (Object.keys(MATRIX) as Role[]).flatMap((r) => MATRIX[r].map((a) => `  ('${ROLE_ENUM[r]}', '${a}')`));
  return `-- GENERATED by tools/gen-permissions-sql.ts from src/lib/permissions.ts. Do not edit by hand.
-- Requirements section 17, "Permissions matrix". Deny by default: a role with no row here can do nothing.
insert into public.role_permissions (role, action) values
${rows.join(",\n")}
on conflict do nothing;
`;
}

if (process.argv[1]?.endsWith("gen-permissions-sql.ts")) {
  fs.writeFileSync("src/lib/db/migrations/0002_permissions_seed.sql", permissionsSql());
  console.log("wrote 0002_permissions_seed.sql");
}
