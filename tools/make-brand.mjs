// Dev-only: turns the two logo files Devatop supplied (white background) into transparent PNGs, the Devatop mark on its own,
// the browser tab icon (src/app/icon.png + favicon.ico) and the install icons. Run: node tools/make-brand.mjs <devatop.jpg> <talkam.jpg>
import sharp from "sharp";
import fs from "node:fs";
const [devatop, talkam] = process.argv.slice(2);

/** White becomes transparent (soft edge), then trim the empty border. `blank` clears stray marks in the given top rows. */
async function clean(file, blankTop = 0) {
  const { data, info } = await sharp(file).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  for (let i = 0; i < data.length; i += 4) {
    const d = 255 - Math.min(data[i], data[i + 1], data[i + 2]);
    data[i + 3] = d < 14 ? 0 : d > 70 ? 255 : Math.round(((d - 14) / 56) * 255);
  }
  for (let y = 0; y < blankTop; y++) for (let x = 0; x < info.width; x++) data[(y * info.width + x) * 4 + 3] = 0;
  return crop(await sharp(data, { raw: info }).png().toBuffer(), 0, 0, 1, 1);
}

/** Crops to a fraction of the picture, then to the box that holds visible pixels (alpha above 40), ignoring faint specks. */
async function crop(png, left, top, w, h) {
  const meta = await sharp(png).metadata();
  const region = await sharp(png).extract({ left: Math.round(left * meta.width), top: Math.round(top * meta.height), width: Math.round(w * meta.width), height: Math.round(h * meta.height) }).toBuffer();
  const { data, info } = await sharp(region).raw().toBuffer({ resolveWithObject: true });
  let x0 = info.width, y0 = info.height, x1 = -1, y1 = -1;
  for (let y = 0; y < info.height; y++) for (let x = 0; x < info.width; x++) if (data[(y * info.width + x) * 4 + 3] > 40) { x0 = Math.min(x0, x); x1 = Math.max(x1, x); y0 = Math.min(y0, y); y1 = Math.max(y1, y); }
  return sharp(region).extract({ left: x0, top: y0, width: x1 - x0 + 1, height: y1 - y0 + 1 });
}
const full = await clean(devatop, 16), talk = await clean(talkam);
const fullPng = await full.clone().png().toBuffer();
await sharp(fullPng).resize({ width: 640 }).png({ compressionLevel: 9, palette: true, quality: 90 }).toFile("public/brand/devatop-logo.png"); // web sizes: light on phones
await talk.clone().resize({ width: 480 }).png({ compressionLevel: 9, palette: true, quality: 90 }).toFile("public/brand/talkam-logo.png");

// the mark: the figures and crescent, above the words
const mark = await crop(fullPng, 0, 0, 1, 0.6);
await mark.clone().resize({ width: 320 }).png({ compressionLevel: 9, palette: true, quality: 90 }).toFile("public/brand/devatop-mark.png");

const square = async (size, bg, scale) => {
  const m = await mark.clone().resize({ width: Math.round(size * scale), height: Math.round(size * scale), fit: "inside" }).png().toBuffer();
  return sharp({ create: { width: size, height: size, channels: 4, background: bg } }).composite([{ input: m, gravity: "centre" }]).png();
};
const clear = { r: 0, g: 0, b: 0, alpha: 0 }, paper = { r: 242, g: 237, b: 227, alpha: 1 };
await (await square(128, clear, 0.98)).toFile("src/app/icon.png");
await (await square(192, paper, 0.8)).toFile("public/icons/icon-192.png");
await (await square(512, paper, 0.8)).toFile("public/icons/icon-512.png");
await (await square(512, paper, 0.56)).toFile("public/icons/maskable-512.png");
await (await square(180, paper, 0.8)).toFile("public/icons/apple-touch-icon.png");

// favicon.ico with 16, 32 and 48 px PNG images inside
const sizes = [16, 32, 48], pngs = await Promise.all(sizes.map(async (s) => (await square(s, clear, 0.98)).toBuffer()));
const head = Buffer.alloc(6); head.writeUInt16LE(1, 2); head.writeUInt16LE(sizes.length, 4);
let offset = 6 + 16 * sizes.length;
const dir = sizes.map((s, i) => { const e = Buffer.alloc(16); e[0] = s; e[1] = s; e.writeUInt16LE(1, 4); e.writeUInt16LE(32, 6); e.writeUInt32LE(pngs[i].length, 8); e.writeUInt32LE(offset, 12); offset += pngs[i].length; return e; });
fs.writeFileSync("src/app/favicon.ico", Buffer.concat([head, ...dir, ...pngs]));

// the mark as text, for the certificate PDF (serverless functions cannot rely on reading files from /public)
const pdfMark = await mark.clone().resize({ width: 240 }).png({ compressionLevel: 9 }).toBuffer();
fs.writeFileSync("src/lib/pdf/brandMark.ts", `// Generated by tools/make-brand.mjs. Do not edit.\nexport const DEVATOP_MARK = "data:image/png;base64,${pdfMark.toString("base64")}";\n`);
