import fs from 'fs';
const g = JSON.parse(fs.readFileSync('tools/nga.json','utf8'));
// equirectangular w/ cos(lat) correction
const lat0 = 9, k = Math.cos(lat0*Math.PI/180);
const proj = ([x,y]) => [x*k, -y];
let minX=1e9,minY=1e9,maxX=-1e9,maxY=-1e9;
const feats = g.features.map(f=>{
  const polys = f.geometry.type==='Polygon'?[f.geometry.coordinates]:f.geometry.coordinates;
  return {name:f.properties.NAME_1, polys: polys.map(p=>p.map(r=>r.map(proj)))};
});
feats.forEach(f=>f.polys.forEach(p=>p.forEach(r=>r.forEach(([x,y])=>{minX=Math.min(minX,x);maxX=Math.max(maxX,x);minY=Math.min(minY,y);maxY=Math.max(maxY,y);}))));
const W=800, s=W/(maxX-minX), H=Math.round((maxY-minY)*s);
// simplify: Douglas-Peucker
const dp=(pts,eps)=>{ if(pts.length<3) return pts; const [a,b]=[pts[0],pts.at(-1)]; let md=0,mi=0;
 for(let i=1;i<pts.length-1;i++){const d=dist(pts[i],a,b); if(d>md){md=d;mi=i;}}
 if(md>eps) return [...dp(pts.slice(0,mi+1),eps).slice(0,-1),...dp(pts.slice(mi),eps)]; return [a,b]; };
const dist=(p,a,b)=>{const dx=b[0]-a[0],dy=b[1]-a[1];const l=dx*dx+dy*dy; if(!l) return Math.hypot(p[0]-a[0],p[1]-a[1]); const t=Math.max(0,Math.min(1,((p[0]-a[0])*dx+(p[1]-a[1])*dy)/l)); return Math.hypot(p[0]-a[0]-t*dx,p[1]-a[1]-t*dy);};
const out = feats.map(f=>{
  let d=''; let cx=0,cy=0,n=0;
  f.polys.forEach(p=>{ const r=p[0].map(([x,y])=>[(x-minX)*s,(y-minY)*s]); const sr=dp(r,0.9);
    if(sr.length<4) return; d+='M'+sr.map(([x,y])=>x.toFixed(1)+' '+y.toFixed(1)).join('L')+'Z';
    // centroid of biggest
    sr.forEach(([x,y])=>{cx+=x;cy+=y;n++;}); });
  return {id:f.name.replace(/\s+/g,'-').toLowerCase().replace('nassarawa','nasarawa'), name:f.name, d, cx:+(cx/n).toFixed(0), cy:+(cy/n).toFixed(0)};
});
fs.mkdirSync('src/lib',{recursive:true});
fs.writeFileSync('src/lib/nigeria-map.ts', `// Generated by tools/mkmap.mjs from GADM 4.1 (simplified). Do not edit by hand.\nexport const MAP_W = ${W};\nexport const MAP_H = ${H};\nexport const STATES = ${JSON.stringify(out)} as { id: string; name: string; d: string; cx: number; cy: number }[];\n`);
console.log(out.length, W, H, fs.statSync('src/lib/nigeria-map.ts').size);
